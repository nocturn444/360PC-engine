-- compat_check: run a game on official LÖVE 11.x (PC) and be told what it uses that the console
-- does not have. Copy this file and api_subset_data.lua into the game folder and require it first
-- thing in main.lua:
--     local compat = require("compat_check")
--     -- compat.install({ file = "compat_check.txt" })   -- also append the lines to that file in the save folder
-- Every function of the love modules and every method of LÖVE's object types is wrapped. The
-- wrappers only look: calls, arguments, results and errors pass through unchanged. A line is
-- printed, once per name, when the game calls
--   * something that is not in the console's subset (docs/API_SUBSET.md),
--   * a stub (exists on the console, does nothing useful),
--   * a partial function in a way the console does not support, where the arguments show it
--     (M.checks below),
-- or defines a callback the console never calls. compat.report() prints the totals.
-- Not required: no effect at all. Required on the console: does nothing.
-- The list comes from api_subset_data.lua, generated by tools/gen_api_subset.lua.
local M = {}
local data = require(((...) or 'compat_check'):gsub('compat_check$', 'api_subset_data'))
M.data = data

local select, type, tostring, pairs, ipairs, rawget, rawset = select, type, tostring, pairs, ipairs, rawget, rawset
local raw_print = print

-- LÖVE's own love.run calls these every frame: their being stubs on the console says nothing
-- about the game.
local QUIET = { ['love.event.pump'] = true, ['love.event.poll'] = true }
-- Tables in love that are not modules
local NOT_MODULES = { handlers = true, arg = true }
-- The functions of the love table itself that are API (the rest are callbacks and LÖVE's boot)
local TOP_LEVEL = { getVersion = true, isVersionCompatible = true, setDeprecationOutput = true,
  hasDeprecationOutput = true }

---------------------------------------------------------------------------
-- State
---------------------------------------------------------------------------
local state               -- nil until install()
local function new_state()
  return {
    love = nil, print = raw_print, file = nil, append = nil, read = nil,
    wrapped = {},           -- wrapper -> true, so that install() can be called again
    used = {},              -- name -> true, every wrapped function the game called
    used_count = 0,
    lines = {},             -- the lines printed, in order
    seen = {},              -- line -> true
    counts = { missing = 0, stub = 0, limit = 0, callback = 0 },
    defaults = {},          -- callbacks LÖVE itself defines (love.run, love.errorhandler...)
    drawables = setmetatable({}, { __mode = 'k' }),
    shaders = nil,          -- game.lua's declared shader files, read on the first newShader
  }
end

local function warn(kind, name, text)
  local line = '[compat] ' .. name .. ': ' .. text
  local s = state
  if s.seen[line] then return end
  s.seen[line] = true
  s.lines[#s.lines + 1] = line
  s.counts[kind] = s.counts[kind] + 1
  s.print(line)
  if s.file and s.append then pcall(s.append, s.file, line .. '\n') end
end

---------------------------------------------------------------------------
-- Argument checks for partial functions: key -> function(...) returning nil (fine on the
-- console) or what is not supported. Methods get the object first. They must be cheap and must
-- not touch their arguments. tools/gen_api_subset.lua checks that every key is a partial function.
---------------------------------------------------------------------------
local function ext(path) return (tostring(path):match('%.([%w]+)$') or ''):lower() end
local function count_points(first, ...)
  if type(first) == 'table' then return #first / 2 end
  return select('#', first, ...) / 2
end
local function filter_check(min, mag)
  if mag ~= nil and mag ~= min then return 'min "' .. tostring(min) .. '" and mag "' .. tostring(mag)
    .. '": the console uses the first for both' end
end
local function samples_check(unit)
  if unit == 'samples' then return 'the "samples" unit is not supported on the console (seconds only)' end
end

-- game.lua's shaders: { files = { path = true }, codes = { text = true } }, or false without a game.lua
local function declared_shaders()
  local s = state
  if s.shaders ~= nil then return s.shaders end
  s.shaders = false
  local src = s.read and s.read('game.lua')
  local chunk = type(src) == 'string' and (loadstring or load)(src, '@game.lua')
  if not chunk then return false end
  if setfenv then setfenv(chunk, {}) end
  local ok, cfg = pcall(chunk)
  if not ok or type(cfg) ~= 'table' then return false end
  local found = { files = {}, codes = {} }
  if type(cfg.shaders) == 'table' then
    for _, d in pairs(cfg.shaders) do
      if type(d) == 'string' then d = { d } end
      if type(d) == 'table' then
        for _, path in pairs(d) do
          path = tostring(path):gsub('\\', '/'):gsub('^%./', '')
          found.files[path] = true
          local code = s.read(path)
          if type(code) == 'string' then found.codes[code:gsub('\r\n', '\n')] = true end
        end
      end
    end
  end
  s.shaders = found
  return found
end
local function shader_arg(src)
  if type(src) ~= 'string' then return 'a ' .. type(src) .. ' argument: the console takes a file name' end
  local declared = declared_shaders()
  if src:find('\n', 1, true) then
    if declared and declared.codes[src:gsub('\r\n', '\n')] then return nil end
    return 'shader code in a string: the console only has the shaders declared in game.lua (shaders), '
      .. 'built on PC; put the code in a file, declare it and pass the file name'
  end
  if declared and not declared.files[src:gsub('\\', '/'):gsub('^%./', '')] then
    return '"' .. src .. '" is not declared in game.lua (shaders): drawn with the default shader on the console'
  end
end

local DRAWABLE = { Image = true, Canvas = true, SpriteBatch = true, ParticleSystem = true, Text = true }

M.checks = {
  ['love.graphics.setBlendMode'] = function(mode)
    if mode ~= 'alpha' and mode ~= 'add' then
      return '"' .. tostring(mode) .. '" is drawn as "alpha" on the console (only "alpha" and "add")'
    end
  end,
  ['love.graphics.newShader'] = function(a, b)
    return shader_arg(a) or (b ~= nil and shader_arg(b)) or nil
  end,
  ['love.graphics.newCanvas'] = function(w, h)
    if (w ~= nil and w ~= 1280) or (h ~= nil and h ~= 720) then
      return 'a ' .. tostring(w) .. 'x' .. tostring(h) .. ' canvas: on the console every canvas is 1280x720'
    end
  end,
  ['love.graphics.setCanvas'] = function(c)
    if type(c) == 'table' and (#c > 1 or c.stencil or c.depthstencil or c.depth) then
      return 'several canvases, stencil or depth: the console draws to one canvas, without stencil or depth'
    end
  end,
  ['love.graphics.push'] = function(kind)
    if kind == 'all' then return 'push("all") only saves the transform on the console' end
  end,
  ['love.graphics.newImage'] = function(src)
    if type(src) ~= 'string' then return 'not a file name (ImageData, FileData...): the console loads PNG files by name' end
    if ext(src) ~= 'png' then return '".' .. ext(src) .. '" file: the console loads PNG only' end
  end,
  ['love.graphics.newFont'] = function(src)
    if type(src) == 'string' then
      if ext(src) ~= 'ttf' then return '".' .. ext(src) .. '" file: the console loads TTF only' end
    elseif src ~= nil and type(src) ~= 'number' then
      return 'not a file name or a size (Rasterizer, FileData...): the console loads TTF files by name'
    end
  end,
  ['love.graphics.rectangle'] = function(_, _, _, _, _, rx, ry)
    if (rx and rx ~= 0) or (ry and ry ~= 0) then return 'rounded corners are not drawn on the console' end
  end,
  ['love.graphics.polygon'] = function(_, ...)
    if count_points(...) > 128 then return 'more than 128 points: the console stops at 128' end
  end,
  ['love.graphics.line'] = function(...)
    if count_points(...) > 510 then return 'more than 510 points: the console stops at 510' end
  end,
  ['love.graphics.setDefaultFilter'] = filter_check,
  ['love.graphics.draw'] = function(what)
    if type(what) ~= 'userdata' then return nil end
    local known = state.drawables[what]
    if known == nil then
      local ok, kind = pcall(function() return what:type() end)
      known = (ok and DRAWABLE[kind]) and true or (ok and tostring(kind) or 'object')
      state.drawables[what] = known
    end
    if known ~= true then return 'a ' .. known .. ': the console draws Image, Canvas, SpriteBatch, ParticleSystem and Text' end
  end,
  ['love.filesystem.read'] = function(a, b)
    if a == 'data' or a == 'string' or type(b) == 'number' then
      return 'a container type or a size: the console reads the whole file as a string'
    end
  end,
  ['love.audio.newSource'] = function(src)
    if type(src) == 'string' and src:sub(1, 4) ~= 'RIFF' then
      local e = ext(src)
      if e ~= 'wav' and e ~= 'ogg' then return '".' .. e .. '" file: the console plays WAV (and .ogg converted to .wav)' end
    end
  end,
  ['love.event.quit'] = function(what)
    if what == 'restart' then return '"restart" leaves the game on the console' end
  end,
  ['love.event.push'] = function(name)
    if name ~= 'quit' then return '"' .. tostring(name) .. '" is dropped on the console (only "quit")' end
  end,
  ['Image:setFilter'] = function(_, min, mag) return filter_check(min, mag) end,
  ['Canvas:setFilter'] = function(_, min, mag) return filter_check(min, mag) end,
  ['ParticleSystem:setSizes'] = function(_, ...)
    if select('#', ...) > 8 then return 'more than 8 sizes' end
  end,
  ['ParticleSystem:setColors'] = function(_, first, ...)
    local n = select('#', ...) + 1
    if type(first) ~= 'table' then n = n / 4 end
    if n > 8 then return 'more than 8 colours' end
  end,
  ['ParticleSystem:setQuads'] = function(_, first, ...)
    local n = type(first) == 'table' and #first or select('#', ...) + 1
    if n > 64 then return 'more than 64 quads' end
  end,
  ['Source:seek'] = function(_, _, unit) return samples_check(unit) end,
  ['Source:tell'] = function(_, unit) return samples_check(unit) end,
}

---------------------------------------------------------------------------
-- Wrapping
---------------------------------------------------------------------------
-- LÖVE's own Lua code (boot.lua, wrap_*.lua) is loaded under chunk names like
-- '=[love "wrap_Graphics.lua"]'. A call from there is LÖVE working inside one of its own
-- functions (newShader asks getSupported, poll asks poll_i), not the game, so it is not counted.
local getinfo = debug and debug.getinfo
local function from_love(level)
  if not getinfo then return false end
  local info = getinfo(level + 1, 'S')
  return info ~= nil and type(info.source) == 'string' and info.source:sub(1, 7) == '=[love '
end

-- Names LÖVE keeps for itself: "_shaderCodeToGLSL", "poll_i". Never the game's API.
local function internal_name(k)
  return k:sub(1, 1) == '_' or k:sub(-2) == '_i'
end

local function status_of(entry)
  if type(entry) == 'table' then return entry[1], entry[2] end
  return entry, nil
end

-- name: "love.graphics.draw" or "Image:getWidth"; entry: its entry in the data, or nil if the
-- console does not have it; why: for a missing one, a reason (an absent module).
local function wrap(fn, name, entry, why)
  local s = state
  local status, note = status_of(entry)
  local check = M.checks[name]
  local wrapper
  if status == nil then
    local text = 'not on the console (missing' .. (why and ': ' .. why or '') .. ')'
    wrapper = function(...)
      if not s.used[name] and not from_love(2) then s.used[name] = true; s.used_count = s.used_count + 1; warn('missing', name, text) end
      return fn(...)
    end
  elseif status == 'stub' and not QUIET[name] then
    local text = 'a stub on the console (' .. (note or 'does nothing') .. ')'
    wrapper = function(...)
      if not s.used[name] and not from_love(2) then s.used[name] = true; s.used_count = s.used_count + 1; warn('stub', name, text) end
      return fn(...)
    end
  elseif check then
    wrapper = function(...)
      if not s.used[name] and not from_love(2) then s.used[name] = true; s.used_count = s.used_count + 1 end
      local ok, text = pcall(check, ...)
      if ok and text then warn('limit', name, text) end
      return fn(...)
    end
  else
    wrapper = function(...)
      if not s.used[name] and not from_love(2) then s.used[name] = true; s.used_count = s.used_count + 1 end
      return fn(...)
    end
  end
  s.wrapped[wrapper] = true
  return wrapper
end

local function wrap_table(t, prefix, entries, why)
  local names = {}
  for k, v in pairs(t) do
    if type(k) == 'string' and type(v) == 'function' and not internal_name(k) and not state.wrapped[v] then
      names[#names + 1] = k
    end
  end
  for _, k in ipairs(names) do
    rawset(t, k, wrap(rawget(t, k), prefix .. k, entries and entries[k], why))
  end
  return #names
end

-- The callbacks the game has defined that the console never calls
function M.check_callbacks()
  local s = state
  if not s then return end
  for name, entry in pairs(data.callbacks) do
    local status, note = status_of(entry)
    local f = rawget(s.love, name)
    if status == 'never' and f ~= nil and f ~= s.defaults[name] then
      warn('callback', 'love.' .. name, 'the console never calls it (' .. (note or 'never called') .. ')')
    end
  end
end

-- install([opts]): wraps what is in the love table now. Safe to call again (after more modules
-- are loaded, or to set the file): what is already wrapped is left alone.
-- opts.file: also append every line to this file in the save folder.
-- opts.print: the function that gets each line (default: print).
-- opts.love, opts.registry: the love table and the table of object metatables by type name
--   (default: the global love and debug.getregistry()); for tests.
function M.install(opts)
  opts = opts or {}
  local lv = opts.love or (state and state.love) or rawget(_G, 'love')
  if type(lv) ~= 'table' then return M end
  if rawget(_G, 'l360') and not opts.love then return M end   -- on the console: nothing to check
  local first = state == nil
  if first then
    state = new_state()
    state.love = lv
    for name in pairs(data.callbacks) do state.defaults[name] = rawget(lv, name) end
    -- the real functions, before they are wrapped, for the log file and game.lua
    local fs = rawget(lv, 'filesystem')
    if type(fs) == 'table' then state.append, state.read = fs.append, fs.read end
  end
  local s = state
  if opts.print then s.print = opts.print end
  if opts.file then s.file = opts.file end

  for k, v in pairs(lv) do
    if type(v) == 'function' and TOP_LEVEL[k] and not s.wrapped[v] then
      rawset(lv, k, wrap(v, 'love.' .. k, data.modules['love'][k]))
    end
  end
  for k, v in pairs(lv) do
    if type(k) == 'string' and type(v) == 'table' and not NOT_MODULES[k] and k:sub(1, 1) ~= '_' then
      local name = 'love.' .. k
      local why = data.modules[name] == nil
        and ('there is no ' .. name .. (data.absent_modules[name] and '. ' .. data.absent_modules[name] or '')) or nil
      wrap_table(v, name .. '.', data.modules[name], why)
    end
  end
  -- LÖVE keeps each object type's metatable (its methods) in the registry under the type's name
  local registry = opts.registry or (debug and debug.getregistry and debug.getregistry()) or {}
  for name, entries in pairs(data.types) do
    local mt = registry[name]
    if type(mt) == 'table' then
      wrap_table(mt, name .. ':', entries)
      local index = rawget(mt, '__index')
      if type(index) == 'table' and index ~= mt then wrap_table(index, name .. ':', entries) end
    end
  end
  -- Callbacks: seen when the game defines them (love has no metatable in LÖVE 11), and again in report()
  if first and getmetatable(lv) == nil then
    setmetatable(lv, { __newindex = function(t, k, v)
      rawset(t, k, v)
      local status, note = status_of(data.callbacks[k])
      if status == 'never' and v ~= nil then
        warn('callback', 'love.' .. tostring(k), 'the console never calls it (' .. (note or 'never called') .. ')')
      end
    end })
  end
  M.check_callbacks()
  return M
end

-- report(): prints the totals and every line again; returns the counts
-- { called, missing, stub, limit, callback, total }.
function M.report()
  if not state then
    raw_print('[compat] not installed (no love table, or running on the console)')
    return { called = 0, missing = 0, stub = 0, limit = 0, callback = 0, total = 0 }
  end
  M.check_callbacks()
  local s, c = state, state.counts
  local out = { called = s.used_count, missing = c.missing, stub = c.stub, limit = c.limit, callback = c.callback }
  out.total = c.missing + c.stub + c.limit + c.callback
  s.print(string.format('[compat] report: %d LÖVE functions called; %d missing on the console, %d stubs, '
    .. '%d used beyond a limit, %d callbacks never called', out.called, out.missing, out.stub, out.limit, out.callback))
  for _, line in ipairs(s.lines) do s.print(line) end
  if out.total == 0 then s.print('[compat] nothing outside the console subset was seen in this run') end
  return out
end

-- The lines so far (a copy)
function M.lines()
  local out = {}
  for i, line in ipairs(state and state.lines or {}) do out[i] = line end
  return out
end

M.install()
return M
